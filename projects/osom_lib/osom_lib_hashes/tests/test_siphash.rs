fn test_siphash(#[case] key: &[u8], #[case] input: &[u8], #[case] expected: &[u8]) {
    let mut hash = SipHash::for_slice_key(key);
    hash.update(input);
    let block = hash.result();
    assert_eq!(&block, expected);
}

