use rstest::rstest;

use osom_lib_numbers::gcd::{gcd_32, gcd_64};

#[rstest]
#[case(0, 0, 0)]
#[case(0, 1, 1)]
#[case(1, 1, 1)]
#[case(2, 3, 1)]
#[case(4, 6, 2)]
#[case(15, 12, 3)]
#[case(8*5*17, 4*3*17, 4*17)]
#[case(12, 18, 6)]
#[case(145, 145, 145)]
#[case(1_000_000_000, 1_000_000_000, 1_000_000_000)]
#[case(2_147_483_648, 3_221_225_472, 1_073_741_824)] // 2^31, 3·2^30 → 2^30
#[case(4_294_967_295, 4_294_967_295, 4_294_967_295)] // u32::MAX
#[case(4_294_967_295, 65_537, 65_537)]
#[case(999_999_937, 999_999_929, 1)]
fn test_gcd_32(#[case] a: u32, #[case] b: u32, #[case] expected: u32) {
    assert_eq!(gcd_32(a, b), expected);
    assert_eq!(gcd_32(b, a), expected);
}

#[rstest]
#[case(0, 0, 0)]
#[case(0, 1, 1)]
#[case(1, 1, 1)]
#[case(2, 3, 1)]
#[case(4, 6, 2)]
#[case(15, 12, 3)]
#[case(8*5*17, 4*3*17, 4*17)]
#[case(12, 18, 6)]
#[case(145, 145, 145)]
#[case(10_000_000_000_000_000_000, 5_000_000_000_000_000_000, 5_000_000_000_000_000_000)]
#[case(9_223_372_036_854_775_808, 13_835_058_055_282_163_712, 4_611_686_018_427_387_904)] // 2^63, 3·2^62 → 2^62
#[case(18_446_744_073_709_551_615, 18_446_744_073_709_551_615, 18_446_744_073_709_551_615)] // u64::MAX
#[case(18_446_744_073_709_551_615, 65_537, 65_537)]
#[case(9_999_999_999_999_999_937, 9_999_999_999_999_999_929, 1)]
fn test_gcd_64(#[case] a: u64, #[case] b: u64, #[case] expected: u64) {
    assert_eq!(gcd_64(a, b), expected);
    assert_eq!(gcd_64(b, a), expected);
}
